#!/usr/bin/env bash
# rmw_rss_breakdown.sh - where an rmw's peak resident memory lives, per mapping, for the rmw same-host cells, on the PC.
#
# Why (2026-10-09): the rig's rmw same-host run at a7e02807 had rmw_tickle's peak RSS 0.1-0.6 MB above CycloneDDS's in
# six rows. VmHWM is one number; this says which mappings hold it. Each run is one rmw_samehost_cell.sh cell, unchanged,
# in a private netns with a private /dev/shm (as rmw_samehost.sh's preflight runs it), plus a watcher that reads every
# role's VmRSS every 0.1 s and keeps /proc/PID/smaps from the moment its RSS was highest.
#
# Arms are LABEL=INSTALL[,PERF_INSTALL]: INSTALL is a colcon install holding rmw_tickle and rmw_perf_pingpong,
# PERF_INSTALL one holding a perf_test whose TickLE typesupport was generated against that rmw_tickle (default $PERF_WS;
# rmw_tickle refuses a perf_test generated by another typesupport). The label's middleware comes from its name:
# cyclonedds* runs rmw_cyclonedds_cpp (with INSTALL's ping/pong), anything else rmw_tickle from INSTALL.
#
# HOW TO READ IT, written before running:
#   - Per role, the snapshot at peak RSS split into: heap ([heap]), anon (unnamed mappings: large callocs, thread
#     stacks), shm (/dev/shm and memfd), lib:<name> per shared object, other files. Rss and Anonymous per class.
#   - VOID for a role with no snapshot, or whose snapshot peak is more than 5% below its VmHWM (the watcher missed the
#     peak), or a cell whose sampler saw no traffic (the cell's own summary decides that; this only splits memory).
#   - The question is the DIFFERENCE between arms in the same cell, class by class. A class whose Rss differs by less
#     than 64 kB between repetitions of one arm is noise; the reps line shows it.
#   - The control: classes that no rmw change can touch (libc, libstdc++, rclcpp) must agree across tickle builds
#     within that noise. If they do not, the builds differ in more than rmw_tickle and the comparison is void.
#
# Usage: rmw_rss_breakdown.sh OUT_DIR "label=install ..." "kind:msg:qos[:wait] ..." [reps]
set -uo pipefail
OUT=${1:?out dir} ARMS=${2:?arms} CELLS=${3:?cells} REPS=${4:-2}
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
CELL=$HERE/rmw_samehost_cell.sh
PERF_WS=${PERF_WS:-/tmp/keepall_evict/perf/install}
mkdir -p "$OUT" || exit 1
ns=rssbd_$$
cleanup() { sudo -n ip netns del "$ns" 2>/dev/null; }
trap cleanup EXIT # the only EXIT trap
sudo -n ip netns add "$ns" || { echo "FAIL: cannot create netns $ns"; exit 1; }
sudo -n ip -n "$ns" link set lo up multicast on
sudo -n ip -n "$ns" route add default dev lo

cat >"$OUT/watch.py" <<'PY'
# watch.py <cell dir> <roles>: per role, /proc/PID/smaps at the highest VmRSS seen (<role>.smaps), and the last VmHWM
# read (<role>.hwm, "pid kB"), until done=1.
import os, sys, time
d, roles = sys.argv[1], sys.argv[2].split(",")
best = {r: 0 for r in roles}
def status(pid):
    v = {}
    with open(f"/proc/{pid}/status") as f:
        for line in f:
            if line.startswith(("VmRSS:", "VmHWM:")):
                v[line.split(":")[0]] = int(line.split()[1])
    return v
deadline = time.time() + 600
while time.time() < deadline:
    for r in roles:
        try:
            with open(f"{d}/{r}.pid") as f:
                pid = int(f.read().strip())
            exe = os.readlink(f"/proc/{pid}/exe")
            if not exe.endswith(("ping_node", "pong_node", "perf_test")):
                continue
            st = status(pid)
            v = st.get("VmRSS", 0)
            with open(f"{d}/{r}.hwm", "w") as f:
                f.write(f"{pid} {st.get('VmHWM', 0)}\n")
            if v > best[r]:
                with open(f"/proc/{pid}/smaps") as f:
                    s = f.read()
                best[r] = v
                with open(f"{d}/{r}.smaps", "w") as f:
                    f.write(f"# VmRSS {v}\n" + s)
        except (OSError, ValueError):
            pass
    try:
        with open(f"{d}/meta.txt") as f:
            if "done=1" in f.read():
                break
    except OSError:
        pass
    time.sleep(0.1)
PY

for rep in $(seq 1 "$REPS"); do
    for c in $CELLS; do
        IFS=: read -r kind msg qos wait <<<"$c"
        for arm in $ARMS; do
            label=${arm%%=*} inst=${arm#*=} perf=$PERF_WS
            case "$inst" in *,*) perf=${inst#*,} inst=${inst%%,*} ;; esac
            case "$label" in cyclonedds*) a=cyclonedds ;; *) a=tickle ;; esac
            roles=ping,pong
            [ "$kind" = tput ] && roles=pub,sub
            dur=10
            dir="$OUT/${kind}_${msg}_${qos}${wait:+_$wait}_${label}_r$rep"
            sudo -n ip netns exec "$ns" env -i PATH="$PATH" HOME="$HOME" ARM="$a" KIND="$kind" MSG="$msg" QOS="$qos" \
                WAIT="${wait:-block}" DUR="$dur" RTT_I=0.001 POLL_ARGS="--poll-sleep-us 100" CELL_DIR="$dir" \
                DOMAIN=77 ROS_SETUP=/opt/ros/lyrical/setup.bash OVERLAYS="$inst/local_setup.bash $perf/local_setup.bash" \
                TICKLE_BCAST=127.255.255.255 PINGPONG="$inst/rmw_perf_pingpong/lib/rmw_perf_pingpong" \
                PERF_TEST="$perf/performance_test/lib/performance_test/perf_test" OWNER="$(id -u):$(id -g)" \
                WATCH="$OUT/watch.py" ROLES="$roles" \
                bash -c 'mount -t tmpfs -o size=512m tmpfs /dev/shm || exit 1
                    bash "$0" & cell=$!
                    for _ in $(seq 1 50); do [ -d "$CELL_DIR" ] && break; sleep 0.1; done
                    python3 "$WATCH" "$CELL_DIR" "$ROLES" & w=$!
                    wait $cell; rc=$?; wait $w; chown -R "$OWNER" "$CELL_DIR"; exit $rc' "$CELL"
            echo "$(date +%T) $kind $msg $qos ${wait:-} $label r$rep: cell exit $?"
        done
    done
done
python3 "$HERE/rmw_rss_breakdown_summary.py" "$OUT" | tee "$OUT/summary.txt"
